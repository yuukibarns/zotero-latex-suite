import {build} from "esbuild";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {writeFile} from "node:fs/promises";
import {JSDOM} from "jsdom";
import assert from "node:assert/strict";
import katex from "katex-zotero";
const result = await build({entryPoints:["src/features/print_diagnostic.ts"],bundle:true,format:"esm",write:false});
const {embeddedPrintCSS,printDocument,printTheme} = await import("data:text/javascript;base64,"+Buffer.from(result.outputFiles[0].text).toString("base64"));
const dom = new JSDOM();
dom.window.document.body.style.backgroundColor = "rgb(32, 33, 36)";
assert.equal(printTheme(dom.window, dom.window.document.body), "dark");
assert.equal(printTheme(dom.window, dom.window.document.body, "light"), "light");
assert.equal(printTheme(dom.window, dom.window.document.body, "invalid"), "dark");
dom.window.document.body.style.backgroundColor = "white";
assert.equal(printTheme(dom.window, dom.window.document.body), "light");
assert.equal(printTheme(dom.window, dom.window.document.body, "dark"), "dark");
assert.ok(printDocument("<p>Dark</p>", "", "dark").includes('data-theme="dark"'));
assert.ok(printDocument("<p>Light</p>", "").includes('data-theme="light"'));
const exec = promisify(execFile);
dom.window.fetch = async url => {
 const {stdout} = await exec("unzip",["-p","/usr/lib/zotero/app/omni.ja",url.replace("resource://zotero/","resource/")],{encoding:"buffer",maxBuffer:5e6});
 return {ok:true,text:async()=>stdout.toString(),blob:async()=>new dom.window.Blob([stdout],{type:"font/woff2"})};
};
const css = await embeddedPrintCSS(dom.window);
assert.ok(!css.includes(".toolbar"));
assert.ok(!css.includes("url(assets/"));
const math = katex.renderToString(String.raw`D_F(p\|q)=\frac12\mathbb{E}_{x\sim p}\left[\left\|\nabla_x\log p(x)-\nabla_x\log q(x)\right\|^2\right]`,{displayMode:true});
const section = '<h2>Interpretation and numerical results</h2><p>The divergence measures the difference between two score functions. This formulation connects a geometric description of probability with practical estimation, without requiring a normalizing constant.</p><div class="ls-print-display">'+math+'</div><p>Intentional <span style="color:#a52a2a">text colors</span> and <span style="background-color:#fff1a8">highlighted passages</span> remain intact.</p><table><thead><tr><th>Method</th><th>Error</th><th>Notes</th></tr></thead><tbody><tr><td>Baseline</td><td>0.084</td><td>Direct estimate</td></tr><tr><td>Regularized</td><td>0.031</td><td>Stable across samples</td></tr></tbody></table><blockquote><p>The equation is kept together, while surrounding text can flow between pages.</p></blockquote>';
const html = printDocument('<div class="primary-editor"><h1>Score matching and Fisher divergence</h1><p>A short mathematical note with equations, tables, and annotated observations.</p>'+section.repeat(3)+'</div>',css);
assert.ok(html.includes("table-header-group"));
assert.ok(html.includes("orphans: 3"));
if (process.argv[2]) await writeFile(process.argv[2],html);
dom.window.close();
console.log("Print layout and embedded font checks passed.");
