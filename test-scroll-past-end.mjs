import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {installScrollPastEnd} from './build/test-exports.mjs';
const win=new JSDOM('<html><head></head><body></body></html>',{pretendToBeVisual:true}).window;
let callback,observed=null,disconnects=0;
win.ResizeObserver=class {constructor(cb){callback=cb;}observe(el){observed=el;}disconnect(){observed=null;disconnects++;}};
const tick=()=>new Promise(resolve=>win.requestAnimationFrame(()=>win.requestAnimationFrame(resolve)));
const stop=installScrollPastEnd(win);await tick();
const style=win.document.getElementById('latex-suite-scroll-past-end');assert.equal(style.textContent,'');
win.document.body.innerHTML='<div class="editor-core"><div class="primary-editor" contenteditable="true" style="font-size:16px;line-height:24px"><p>Last line</p></div></div>';
const owner=win.document.querySelector('.editor-core'),editor=owner.firstChild;
let height=600;Object.defineProperty(owner,'clientHeight',{get:()=>height});
const original=editor.outerHTML;
await tick();assert.equal(observed,owner);assert.ok(style.textContent.includes('576px'));
assert.equal(editor.outerHTML,original,'no saved DOM attributes or nodes changed');
assert.ok(!editor.cloneNode(true).outerHTML.includes('576px'),'print clone has no extra spacing');
height=400;callback();await tick();assert.ok(style.textContent.includes('376px'));
editor.setAttribute('contenteditable','false');await tick();assert.equal(style.textContent,'');assert.equal(observed,null);
editor.setAttribute('contenteditable','true');await tick();assert.equal(observed,owner);
owner.remove();await tick();assert.equal(style.textContent,'');
stop();assert.equal(win.document.getElementById('latex-suite-scroll-past-end'),null);assert.ok(disconnects>0);
win.close();console.log('Scroll beyond last line: late init, resize, read-only state, export isolation and cleanup passed.');
