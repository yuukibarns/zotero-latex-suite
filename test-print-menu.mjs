import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { installPrintDiagnostic } from "./build/test-exports.mjs";

const dom = new JSDOM('<div class="toolbar"><div class="more-dropdown"></div></div><div class="primary-editor"><p>Note</p></div>');
const win = dom.window, doc = win.document;
win._currentEditorInstance = { _editorCore: { view: { dom: doc.querySelector(".primary-editor") } } };
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
let resolveCSS, exported = 0, alerts = [];
win.fetch = () => new Promise(resolve => { resolveCSS = () => resolve({ ok: true, text: async () => "body{counter-reset:katexEqnNo mmlEqnNo}" }); });
win.__latexSuiteDiagnosePrint = html => { assert.ok(html.includes("Note")); exported++; };
win.alert = message => alerts.push(message);
const stop = installPrintDiagnostic(win);
assert.equal(doc.querySelector(".toolbar > button"), null);
const open = async () => {
 const menu = doc.createElement("div");
 menu.className = "popup";
 menu.innerHTML = '<button class="option">Native action</button>';
 doc.querySelector(".more-dropdown").append(menu);
 await tick();
 return menu;
};
let menu = await open();
const item = () => doc.querySelector("#latex-suite-print-menu-item");
assert.equal(item().getAttribute("role"), "menuitem");
assert.equal(menu.lastChild, item());
menu.append(doc.createElement("span")); await tick();
assert.equal(doc.querySelectorAll("#latex-suite-print-menu-item").length, 1);
assert.equal(doc.querySelectorAll("#latex-suite-print-menu-separator").length, 1);
let bubbled = false;
menu.addEventListener("click", () => { bubbled = true; menu.remove(); });
item().click(); await tick();
assert.ok(bubbled, "click reaches Zotero's menu dismissal handler");
menu = await open();
assert.equal(item().textContent, "Preparing PDF…");
assert.ok(item().disabled);
item().click(); assert.equal(exported, 0);
resolveCSS(); await tick();
assert.equal(exported, 1); assert.equal(item().disabled, false);
assert.equal(item().textContent, "Print / PDF…");
win.fetch = async () => { throw new Error("Test load failure"); };
item().click(); await tick();
assert.equal(alerts.length, 1); assert.equal(item().disabled, false);
win.fetch = () => new Promise(resolve => { resolveCSS = () => resolve({ok:true,text:async()=>"body{counter-reset:katexEqnNo mmlEqnNo}"}); });
item().click(); stop(); resolveCSS(); await tick();
assert.equal(exported, 1, "teardown cancels pending export");
assert.equal(item(), null);
assert.equal(doc.querySelector("#latex-suite-print-menu-separator"), null);
menu.remove(); await open();
assert.equal(item(), null, "observer is disconnected");
win.close();
console.log("Print menu lifecycle, busy state, bubbling and failure recovery passed.");
