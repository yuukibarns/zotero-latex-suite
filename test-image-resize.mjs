import assert from "node:assert/strict";
import {Schema} from "prosemirror-model";
import {EditorState, NodeSelection, AllSelection} from "prosemirror-state";
import {history, undo, redo} from "prosemirror-history";
import {JSDOM} from "jsdom";
import {commitImageSize, installImageResize} from "./build/test-exports.mjs";
const schema = new Schema({nodes:{
 doc:{content:"image*"},text:{},
 image:{attrs:{width:{default:200},height:{default:100},attachmentKey:{default:"KEY"},annotation:{default:{uri:"test"}}}}
}});
const original = schema.node("doc",null,[schema.node("image")]);
const view = {editable:true,state:EditorState.create({doc:original,selection:NodeSelection.create(original,0),plugins:[history()]})};
view.dispatch = tr => {view.state=view.state.apply(tr);};
view.focus = () => {};
const before = view.state.doc.firstChild;
assert.ok(commitImageSize(view,0,before,400,2));
assert.equal(view.state.doc.firstChild.attrs.height,200);
assert.equal(view.state.doc.firstChild.attrs.attachmentKey,"KEY");
assert.deepEqual(view.state.doc.firstChild.attrs.annotation,{uri:"test"});
assert.equal(commitImageSize(view,0,before,500,2),false,"reject stale node");
assert.ok(undo(view.state,view.dispatch)); assert.ok(view.state.doc.eq(original));
assert.ok(redo(view.state,view.dispatch)); assert.equal(view.state.doc.firstChild.attrs.width,400);
assert.equal(commitImageSize(view,0,view.state.doc.firstChild,Infinity,2),false);
view.editable=false; assert.equal(commitImageSize(view,0,view.state.doc.firstChild,500,2),false); view.editable=true;
const dom=new JSDOM('<div class="primary-editor"><img src="test"></div>',{pretendToBeVisual:true});
const win=dom.window, doc=win.document, img=doc.querySelector("img");
Object.defineProperties(img,{complete:{value:true,configurable:true},naturalWidth:{value:800},naturalHeight:{value:400},offsetWidth:{value:200}});
img.getBoundingClientRect=()=>({left:10,top:50,right:210,bottom:150,width:200,height:100});
view.dom=doc.querySelector(".primary-editor"); view.nodeDOM=()=>img;
win._currentEditorInstance={_editorCore:{view}};
win.prompt=()=>"320";
const stop=installImageResize(win);
const tick=()=>new Promise(r=>win.requestAnimationFrame(()=>win.requestAnimationFrame(r)));
await tick();
const panel=doc.getElementById("latex-suite-image-resize");
assert.equal(panel.style.display,"block");
panel.querySelector("button").click();
assert.equal(view.state.doc.firstChild.attrs.width,320);
const handle=panel.lastChild;
const pointer=(target,type,x)=>{const e=new win.Event(type,{bubbles:true,cancelable:true});Object.assign(e,{button:0,pointerId:1,clientX:x});target.dispatchEvent(e);};
pointer(handle,"pointerdown",210);pointer(doc,"pointermove",310);await tick();
assert.equal(view.state.doc.firstChild.attrs.width,320,"drag does not mutate document");
assert.equal(panel.style.width,"300px");
doc.dispatchEvent(new win.KeyboardEvent("keydown",{key:"Escape",bubbles:true}));
pointer(doc,"pointerup",310);assert.equal(view.state.doc.firstChild.attrs.width,320);
pointer(handle,"pointerdown",210);pointer(doc,"pointermove",310);pointer(doc,"pointerup",310);
assert.equal(view.state.doc.firstChild.attrs.width,300);
assert.ok(undo(view.state,view.dispatch));assert.equal(view.state.doc.firstChild.attrs.width,320);
view.dispatch(view.state.tr.setSelection(new AllSelection(view.state.doc)));
doc.dispatchEvent(new win.Event('selectionchange'));await tick();
assert.equal(panel.style.display,'none');
Object.defineProperty(img,'complete',{value:false,configurable:true});
img.click();await tick();assert.equal(panel.style.display,'none');
Object.defineProperty(img,'complete',{value:true,configurable:true});
img.dispatchEvent(new win.Event('load'));await tick();
assert.equal(panel.style.display,'block','click target activates after loading without NodeSelection');
img.getBoundingClientRect=()=>({left:10,top:-100,right:2010,bottom:1900,width:2000,height:2000});
win.dispatchEvent(new win.Event('resize'));await tick();
assert.ok(parseFloat(handle.style.left)+10 < win.innerWidth);
assert.ok(parseFloat(handle.style.top)-100 < win.innerHeight);
panel.querySelector('button').click();
assert.equal(view.state.doc.firstChild.attrs.width,320,'exact width works without NodeSelection');
doc.body.click();await tick();assert.equal(panel.style.display,'none','click away clears target');
const wrapper=doc.createElement('div');wrapper.className='regular-image';
const inner=doc.createElement('div');inner.className='image';
img.replaceWith(wrapper);wrapper.append(inner);inner.append(img);
view.nodeDOM=()=>wrapper;
pointer(inner,'pointerdown',100);await tick();
assert.equal(panel.style.display,'block','native image wrapper pointer activates controls');
inner.click();await tick();
assert.equal(panel.style.display,'block','wrapper click retains target');
stop();assert.equal(doc.getElementById("latex-suite-image-resize"),null);
win.close();
console.log("Image resizing: metadata, stale/read-only guards, undo/redo, drag, Escape and cleanup passed.");
