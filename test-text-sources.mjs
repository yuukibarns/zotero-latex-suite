import assert from 'node:assert/strict';
import {Schema} from 'prosemirror-model';
import {EditorState,TextSelection} from 'prosemirror-state';
import {WordIndex,BufferWords,TextSources,textToken,parseWordList} from './build/test-exports.mjs';
const schema=new Schema({nodes:{doc:{content:'block+'},text:{group:'inline'},paragraph:{group:'block',content:'inline*'},code_block:{group:'block',content:'text*',code:true},math_display:{group:'block',content:'text*'}},marks:{code:{}}});
const para=(text,type='paragraph')=>schema.node(type,null,text?schema.text(text):null);
const doc=schema.node('doc',null,[para('probability probable café'),para('privateMath','math_display'),para('privateCode','code_block')]);
assert.deepEqual(parseWordList('\uFEFFprobability\r\n\n probability \nprobable'),['probability','probable']);
assert.throws(()=>parseWordList('binary\0'),/NUL/);
const index=new WordIndex(['probability','probable','PROBLEM','problem','other']);
assert.equal(index.match('prob')[0],'problem');
assert.ok(!index.match('problem').includes('problem'));
assert.equal(index.match('PR')[0],'PROBLEM');
const large=new WordIndex(Array.from({length:100000},(_,i)=>'word'+i));
assert.equal(large.match('word99').length,50);
const buffer=new BufferWords();buffer.update(doc);
assert.ok(buffer.match('prob').includes('probability'));
assert.deepEqual(buffer.match('private'),[]);
buffer.update(schema.node('doc',null,[para('replacement')]));
assert.deepEqual(buffer.match('prob'),[],'deleted words removed');
const sources=new TextSources();
const config={bufferCompletionEnabled:true,dictionaryCompletionEnabled:true,textDictionaryWords:'probability\nproblem'};
const merged=sources.match(doc,'prob',config);
assert.equal(merged.filter(row=>row.text==='probability').length,1);
assert.equal(merged.find(row=>row.text==='probability').source,'Buffer');
assert.equal(merged.find(row=>row.text==='problem').source,'Dictionary');
assert.deepEqual(sources.match(doc,'prob',{...config,bufferCompletionEnabled:false,dictionaryCompletionEnabled:false}),[]);
assert.equal(sources.match(doc,'new',{...config,textDictionaryWords:'newWord'})[0].text,'newWord');
function view(text,type='paragraph',offset=text.length) {const doc=schema.node('doc',null,[para(text,type)]);return {state:EditorState.create({doc,selection:TextSelection.create(doc,1+offset)})};}
assert.equal(textToken(view('hello prob')).query,'prob');
assert.equal(textToken(view('café')).query,'café');
for(const text of ['@@prob','hello @@some prob','\\prob','email@prob']) assert.equal(textToken(view(text)),null);
assert.equal(textToken(view('probable','paragraph',4)),null,'middle of token excluded');
assert.equal(textToken(view('prob','math_display')),null);
assert.equal(textToken(view('prob','code_block')),null);
console.log('Buffer/dictionary parsing, indexing, updates, deduplication and token contexts passed.');
